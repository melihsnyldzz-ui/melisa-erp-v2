import express from 'express';
import { rateLimit } from 'express-rate-limit';
import { configureProductionRuntime } from './production-env.mjs';

const configPath = process.argv[2];
if (process.argv.length !== 3) throw Error('PRIVATE_CONFIG_ARGUMENT_REQUIRED');
const { config, env, identity, port } = await configureProductionRuntime(configPath, 'native');
const { securityHeaders } = await import('./src/middleware/security.js');
const { errorHandler } = await import('./src/middleware/errorHandler.js');
const { authRoutes } = await import('./src/routes/authRoutes.js');
const { nativeTerminalRoutes } = await import('./src/routes/nativeTerminalRoutes.mjs');
const { createNativeReceiptPdfShare } = await import('./src/services/nativeReceiptPdfShare.mjs');
const { createNativeReceiptPdfRoutes } = await import('./src/routes/nativeReceiptPdfRoutes.mjs');
const app = express();
app.locals.nativeTerminalV1 = true;
app.locals.nativeReceiptPdfShare = createNativeReceiptPdfShare({ baseUrl: `http://${config.host}:${port}` });
app.disable('x-powered-by');
app.use(securityHeaders());
app.get('/production-switch-health', (_req, res) => res.json({ ok: true, runId: config.runId, releaseId: config.releaseId, databaseName: identity.databaseName, serverName: identity.serverName, loginName: identity.loginName, databaseUser: identity.databaseUser, sysadmin: identity.sysadmin, databaseControl: identity.databaseControl, canInsertSales: identity.canInsertSales, canAlterSales: identity.canAlterSales, mode: 'native', port }));
app.get('/native-terminal-health', (_req, res) => res.json({ ok: true, runId: config.runId, releaseId: config.releaseId, saleTransport: 'melisa', database: identity.databaseName, writeEnabled: !env.sql.readOnly, collectionMode: 'none', negativeStockAllowed: true, automaticSubmit: false, customerRoutesEnabled: config.customerRoutesEnabled === true, packingMode: 'optional-device-helper', receiptPdfShare: 'local-10-minute-link' }));
app.use('/native-receipts', createNativeReceiptPdfRoutes(app.locals.nativeReceiptPdfShare));
app.use(express.json({ limit: '2mb' }));
app.use('/api/auth', rateLimit({ windowMs: 60000, limit: 30, standardHeaders: 'draft-7', legacyHeaders: false }));
app.use('/api', authRoutes);
app.use('/api/native-terminal', nativeTerminalRoutes);
app.use((_req, res) => res.status(404).json({ success: false, error: { code: 'NATIVE_ROUTE_UNAVAILABLE', message: 'Bu işlem terminal kapsamında yok.' } }));
app.use(errorHandler);
const server = app.listen(port, config.host, () => console.log(JSON.stringify({ runId: config.runId, releaseId: config.releaseId, mode: 'native', port, database: identity.databaseName })));
server.on('error', (error) => { console.error(error.code || error.message); process.exitCode = 1; });
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => server.close(() => process.exit(0)));
