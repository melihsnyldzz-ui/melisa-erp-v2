function safeString(value, key) {
  if (value.length > 256) return REDACTED;
  switch (key) {
    case 'requestid': return uuidPattern.test(value) ? value : REDACTED;
    case 'code': return knownCodes.has(value) ? value : REDACTED;
    case 'eventcode': return knownEvents.has(value) ? value : REDACTED;
    case 'category': return knownCategories.has(value) ? value : REDACTED;
    case 'warningcode': return knownWarnings.get(value) || REDACTED;
    case 'method': return /^(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)$/.test(value) ? value : REDACTED;
    case 'nodeenv': return /^(development|test|production)$/.test(value) ? value : REDACTED;
    case 'signal': return /^(SIGINT|SIGTERM)$/.test(value) ? value : REDACTED;
    case 'apiversion': return /^v?\d+(?:\.\d+){0,2}$/.test(value) ? value : REDACTED;
    case 'sqlstatecode': return /^[0-9A-Z]{5}$/.test(value) ? value : REDACTED;
    case 'sqlcall': return isSelectedSaleDiagnosticCall(value) ? value : REDACTED;
    default: return REDACTED;
  }
}

// Use the server's route template, never the client's URL/query or dynamic path values.
export function requestLogPath(req) {
  try {
    const route = req.route?.path;
    const value = typeof route !== 'string' ? '[unmatched route]'
      : route.length <= 256 && /^\/[A-Za-z0-9_/:.*()-]*$/.test(route) ? route : REDACTED;
    const wrapper = Object.freeze(Object.create(null));
    trustedPaths.set(wrapper, value);
    return wrapper;
  } catch {
    return REDACTED;
  }
}

function sanitize(input, key, depth, seen) {
  const normalizedKey = key.toLowerCase().replace(/[^a-z0-9]/g, '');
  if (normalizedKey === 'key' || sensitiveKeyPattern.test(normalizedKey)) return REDACTED;
  if (normalizedKey === 'path') return trustedPaths.has(input) ? trustedPaths.get(input) : REDACTED;
  if (stringFields.has(normalizedKey) && typeof input !== 'string') return REDACTED;
  if (numberFields.has(normalizedKey) && typeof input !== 'number') return REDACTED;
  if (booleanFields.has(normalizedKey) && typeof input !== 'boolean') return REDACTED;
  if (typeof input === 'string') return safeString(input, normalizedKey);
  if (input === null) return null;
  if (typeof input === 'boolean') return booleanFields.has(normalizedKey) ? input : REDACTED;
  if (typeof input === 'number') {
    if (!numberFields.has(normalizedKey) || !Number.isFinite(input)) return REDACTED;
    if (normalizedKey === 'statuscode' && (!Number.isInteger(input) || input < 100 || input > 599)) return REDACTED;
    if (normalizedKey === 'durationms' && input < 0) return REDACTED;
    if (normalizedKey === 'port' && (!Number.isInteger(input) || input < 1 || input > 65535)) return REDACTED;
    if (normalizedKey === 'retryafterseconds' && (!Number.isInteger(input) || input < 1 || input > 900)) return REDACTED;
    const sqlBounds={sqlnumber:[1,2147483647],sqlstate:[0,255],sqlclass:[0,25],sqllinenumber:[0,1000000],sqlcalldurationms:[0,86400000]}[normalizedKey];
    if(sqlBounds&&(!Number.isSafeInteger(input)||input<sqlBounds[0]||input>sqlBounds[1]))return REDACTED;
    return input;
  }
  if (typeof input !== 'object' || depth >= MAX_DEPTH || seen.has(input)) return REDACTED;
  seen.add(input);
  try {
    // Descriptors avoid executing getters or application-provided toJSON methods.
    const descriptors = Object.getOwnPropertyDescriptors(input);
    const array = Array.isArray(input);
    const output = array ? [] : Object.create(null);
    let count = 0;
    let omittedFields = 0;
    for (const [childKey, descriptor] of Object.entries(descriptors)) {
      if (!descriptor.enumerable || childKey === 'toJSON') continue;
      if (array && !/^(0|[1-9]\d*)$/.test(childKey)) continue;
      if (++count > MAX_ENTRIES) {
        if (array) output.push(REDACTED);
        else output.logTruncated = true;
        break;
      }
      const field = array ? '' : fieldNames.get(childKey.toLowerCase().replace(/[^a-z0-9]/g, ''));
      // Unknown names can themselves contain credentials; never copy their spelling.
      if (!array && !field) {omittedFields++; continue;}
      const value = Object.hasOwn(descriptor, 'value')
        ? sanitize(descriptor.value, field, depth + 1, seen)
        : REDACTED;
      if (array) output.push(value);
      else Object.defineProperty(output, field, {value, enumerable: true, configurable: true});
    }
    if (!array && omittedFields) output.omittedFields = omittedFields;
    return output;
  } catch {
    return REDACTED;
  } finally {
    seen.delete(input);
  }
}

export function maskSensitive(input) {
  try {
    return sanitize(input, '', 0, new WeakSet());
  } catch {
    return REDACTED;
  }
}

function write(level, message, meta = {}) {
  const safeMeta = maskSensitive(meta);
  const payload = {
    ...(safeMeta && typeof safeMeta === 'object' && !Array.isArray(safeMeta) ? safeMeta : {}),
    level,
    message: typeof message === 'string' && knownMessages.has(message) ? message : REDACTED,
    timestamp: new Date().toISOString(),
  };

  const line = JSON.stringify(payload);
  if (level === 'error') {
    console.error(line);
  } else if (level === 'warn') {
    console.warn(line);
  } else {
    console.log(line);
  }
}

export const logger = {
  info: (message, meta) => write('info', message, meta),
  warn: (message, meta) => write('warn', message, meta),
  error: (message, meta) => write('error', message, meta),
};
